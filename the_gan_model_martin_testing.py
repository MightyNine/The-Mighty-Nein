# 1. DATASET CLASS
# ============================================================

class AnomalyDataset(Dataset):

    def __init__(
        self,
        csv_file,
        label_col="label",
        normal_label="BenignTraffic",
        target_shape=(16, 16),
        max_samples=None,
        subset_fraction=None,
    ):

        # Check whether train.csv already contains column headers
        train_columns = pd.read_csv(
            csv_file,
            nrows=0
        ).columns.tolist()

        # If train.csv already has the label column, load normally
        if label_col in train_columns:

            self.df = pd.read_csv(csv_file)

        # Otherwise, use the column names from test.csv
        else:

            column_names = pd.read_csv(
                TEST_CSV,
                nrows=0
            ).columns.tolist()

            self.df = pd.read_csv(
                csv_file,
                header=None,
                names=column_names
            )

        # Make sure the label column exists
        if label_col not in self.df.columns:
            raise ValueError(
                f"Could not find '{label_col}' column in training dataset."
            )

        # Keep only benign training traffic
        self.df = self.df[
            self.df[label_col] == normal_label
        ].reset_index(drop=True)

        if len(self.df) == 0:
            raise ValueError(
                f"No '{normal_label}' samples were found in train.csv."
            )

        # Remove label column
        self.df = self.df.drop(
            columns=[label_col]
        )

        # Take a random fraction if requested
        if (
            subset_fraction is not None
            and 0.0 < subset_fraction < 1.0
        ):
            self.df = self.df.sample(
                frac=subset_fraction,
                random_state=42
            ).reset_index(drop=True)

        # Cap maximum samples if requested
        if (
            max_samples is not None
            and len(self.df) > max_samples
        ):
            self.df = self.df.iloc[
                :max_samples
            ].reset_index(drop=True)

        # Keep numerical features only
        self.df = self.df.select_dtypes(
            include=[np.number]
        )

        # Save feature columns for test data
        self.feature_columns = self.df.columns.tolist()

        # Clean invalid values
        self.df = self.df.replace(
            [np.inf, -np.inf],
            np.nan
        )

        self.medians = self.df.median()

        self.df = self.df.fillna(
            self.medians
        )

        # Save training scaling values
        self.data_min = self.df.min()
        self.data_max = self.df.max()

        range_diff = (
            self.data_max - self.data_min
        ).replace(0, 1)

        scaled_features = (
            2 * (self.df - self.data_min) / range_diff
        ) - 1

        scaled_numpy = scaled_features.to_numpy(
            dtype=np.float32
        )

        # Convert data into 16 x 16 GAN input
        total_pixels = (
            target_shape[0] * target_shape[1]
        )

        num_samples, num_features = scaled_numpy.shape

        padded_features = np.zeros(
            (num_samples, total_pixels),
            dtype=np.float32
        )

        padded_features[
            :, :num_features
        ] = scaled_numpy

        reshaped_data = padded_features.reshape(
            -1,
            1,
            target_shape[0],
            target_shape[1]
        )

        self.data = torch.tensor(
            reshaped_data,
            dtype=torch.float32
        )

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        return self.data[idx]


# 2. Generator Network (DCGAN Architecture)
class Generator(nn.Module):

    def __init__(self, z_dim=100, img_channels=1):
        super().__init__()
        self.net = nn.Sequential(
            nn.ConvTranspose2d(z_dim, 256, kernel_size=4, stride=1, padding=0),
            nn.BatchNorm2d(256),
            nn.ReLU(True),
            nn.ConvTranspose2d(256, 128, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(128),
            nn.ReLU(True),
            nn.ConvTranspose2d(
                128, img_channels, kernel_size=4, stride=2, padding=1
            ),
            nn.Tanh(),
        )

    def forward(self, z):
        return self.net(z)


# 3. Discriminator Network (DCGAN Architecture)
class Discriminator(nn.Module):

    def __init__(self, img_channels=1):
        super().__init__()
        self.net = nn.Sequential(
            nn.Conv2d(img_channels, 128, kernel_size=4, stride=2, padding=1),
            nn.LeakyReLU(0.2, inplace=True),
            nn.Conv2d(128, 256, kernel_size=4, stride=2, padding=1),
            nn.BatchNorm2d(256),
            nn.LeakyReLU(0.2, inplace=True),
            nn.Conv2d(256, 1, kernel_size=4, stride=1, padding=0),
            nn.Sigmoid(),
        )

    def forward(self, img):
        return self.net(img)


# ==========================================
# 4. Dataset Hyperparameters for Speedup
# ==========================================
DATASET_CSV = TRAIN_CSV

# Hyperparameters to cut down processing time:
SUBSET_FRACTION = 0.10  # Loads 10% of the normal dataset
MAX_SAMPLES = (
    50000  # Caps total training samples (set to None if using fraction only)
)

dataset = AnomalyDataset(
    csv_file=DATASET_CSV,
    label_col="label",
    normal_label="BenignTraffic",
    target_shape=(16, 16),
    max_samples=MAX_SAMPLES,
    subset_fraction=SUBSET_FRACTION,
)

BATCH_SIZE = 128  # Larger batch size speeds up GPU training
dataloader = DataLoader(
    dataset, batch_size=BATCH_SIZE, shuffle=True, num_workers=2
)

print(
    f"Successfully loaded {len(dataset)} normal training samples from {DATASET_CSV}."
)

# 5. Device & Model Configuration
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
Z_DIM = 100

generator = Generator(z_dim=Z_DIM, img_channels=1).to(device)
discriminator = Discriminator(img_channels=1).to(device)

criterion = nn.BCELoss()
optimizer_G = optim.Adam(generator.parameters(), lr=0.0002, betas=(0.5, 0.999))
optimizer_D = optim.Adam(discriminator.parameters(), lr=0.0002, betas=(0.5, 0.999))

# 6. Training Execution Loop
EPOCHS = 5

for epoch in range(EPOCHS):
    for batch_idx, real_images in enumerate(dataloader):
        batch_size = real_images.size(0)
        real_images = real_images.to(device)

        real_labels = torch.ones(batch_size, 1, 1, 1).to(device)
        fake_labels = torch.zeros(batch_size, 1, 1, 1).to(device)

        # ----------------------
        #  Train Discriminator
        # ----------------------
        optimizer_D.zero_grad()

        output_real = discriminator(real_images)
        loss_D_real = criterion(output_real, real_labels)

        z = torch.randn(batch_size, Z_DIM, 1, 1).to(device)
        fake_images = generator(z)
        output_fake = discriminator(fake_images.detach())
        loss_D_fake = criterion(output_fake, fake_labels)

        loss_D = loss_D_real + loss_D_fake
        loss_D.backward()
        optimizer_D.step()

        # ----------------------
        #  Train Generator
        # ----------------------
        optimizer_G.zero_grad()

        output_fake_for_G = discriminator(fake_images)
        loss_G = criterion(output_fake_for_G, real_labels)

        loss_G.backward()
        optimizer_G.step()

    print(
        f"Epoch [{epoch+1}/{EPOCHS}] | Loss D: {loss_D.item():.4f} | Loss G: {loss_G.item():.4f}"
    )

